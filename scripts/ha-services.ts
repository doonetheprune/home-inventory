/**
 * Builds custom_components/larder/services.yaml (and actions.json) from Larder's own list of
 * actions (core and bundled modules), so Home Assistant's validator and UI
 * see the same names, descriptions and fields the integration registers at
 * runtime. tests/ha-services.test.ts fails if the file is stale: run
 * `npm run ha:services` to refresh it.
 *
 * The field selectors match custom_components/larder/services.py.
 */
import { createCore, type ActionInfo } from '@larder/core';
import { createMemoryStorage } from '../src/adapters/storage-memory';
import { createMemoryFileStore } from '../src/adapters/files-memory';
import { createMemorySearchIndex } from '../src/adapters/search-memory';
import { createMemoryEventBus } from '../src/adapters/events-memory';
import { modules } from '../modules';

const DATE_PATTERN = '^\\d{4}-\\d{2}-\\d{2}$';

type Prop = { type?: string; enum?: string[]; pattern?: string; description?: string; default?: unknown };

function selector(p: Prop): Record<string, unknown> {
  if (p.enum) return { select: { options: p.enum } };
  if (p.type === 'number' || p.type === 'integer') return { number: { mode: 'box', min: 0, step: p.type === 'number' ? 'any' : 1 } };
  if (p.type === 'boolean') return { boolean: {} };
  if (p.type === 'string' && p.pattern === DATE_PATTERN) return { date: {} };
  return { text: {} };
}

const label = (key: string) => key.replace(/_/g, ' ').replace(/^./, (c) => c.toUpperCase());

/** A small YAML writer: enough for nested maps of strings, numbers, booleans and lists. */
function yaml(value: unknown, indent = 0): string {
  const pad = ' '.repeat(indent);
  const scalar = (v: unknown) => (typeof v === 'string' ? JSON.stringify(v) : String(v));
  if (Array.isArray(value)) return value.map((v) => `${pad}- ${scalar(v)}`).join('\n');
  return Object.entries(value as Record<string, unknown>)
    .map(([k, v]) => {
      if (v && typeof v === 'object') {
        const inner = yaml(v, indent + 2);
        return inner ? `${pad}${k}:\n${inner}` : `${pad}${k}: {}`;
      }
      return `${pad}${k}: ${scalar(v)}`;
    })
    .join('\n');
}

export function servicesYaml(actions: ActionInfo[]): string {
  const out: Record<string, unknown> = {};
  for (const a of actions) {
    const schema = a.schema as { properties?: Record<string, Prop>; required?: string[] };
    const required = new Set(schema.required ?? []);
    const fields: Record<string, unknown> = {};
    for (const [key, p] of Object.entries(schema.properties ?? {})) {
      fields[key] = { name: label(key), description: p.description ?? '', required: required.has(key), ...(p.default !== undefined ? { default: p.default } : {}), selector: selector(p) };
    }
    fields.config_entry_id = { name: 'Larder', description: 'Only needed when Home Assistant is linked to more than one Larder.', required: false, advanced: true, selector: { config_entry: { integration: 'larder' } } };
    out[a.id] = { name: a.name, description: a.description, fields };
  }
  return `# Generated by \`npm run ha:services\` from Larder's actions. Don't edit by hand.\n${yaml(out)}\n`;
}

async function bundledActions(): Promise<ActionInfo[]> {
  const core = await createCore(
    { storage: createMemoryStorage(), files: createMemoryFileStore(), search: createMemorySearchIndex(), events: createMemoryEventBus() },
    { modules },
  );
  return core.automation.actions();
}

export async function haServicesYaml(): Promise<string> {
  return servicesYaml(await bundledActions());
}

/**
 * The same actions as JSON, shipped with the integration so they're registered
 * even while Larder can't be reached (they then say so when called).
 */
export async function haActionsJson(): Promise<string> {
  return `${JSON.stringify(await bundledActions(), null, 2)}\n`;
}
